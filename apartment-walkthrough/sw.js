/* Apartment walkthrough: offline shell service worker, scoped to this folder.
   Generated by tools/publish.mjs and registered by the app once its assets are downloaded (so the
   precache below is served from the HTTP cache instead of downloading everything twice). The
   cache name carries a hash of the published files, so every publish invalidates the old cache; the
   "v2" is the version of this layout (one folder of assets per apartment). Install precaches the shell
   only: the page, the list of apartments, the shared decoder and the card pictures. An apartment is
   kept for offline use as it is visited: after its start-up assets have loaded the app posts
   {type: "cache-flat", flat} and the worker adds that apartment's start-up files (from the HTTP cache). So
   an apartment that was never opened is not offline, and the app says so. Lazy assets (rgh_*.png, sky.hdr) are
   cached by the network-first handler when the app first asks for them. Network-first for every same-origin
   file (the page, the app and the assets change together on each publish); this version's cache is only the
   offline fallback. A page for any ?flat= falls back to the cached index.html (the page only: other documents of the scope are cached
   under their own address). After an update the new worker takes over the open page (skipWaiting, claim) and the page asks it again
   to keep its apartment (the request it sent to the outgoing worker went to a cache that is being deleted).
   Cross-origin requests are never intercepted. */
const CACHE = "vibe-apartment-walkthrough-v2-ebdea861d9";
const CACHE_PREFIX = "vibe-apartment-walkthrough-";
const SAFE_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
const FLAT_ID = /^[a-z0-9]{1,16}$/;
const SHELL = ["./", "./index.html", "./styles.css", "./app.js", "./manifest.webmanifest", "./icon.svg", "./assets/flats.json", "./assets/shared/draco_wasm_wrapper.js", "./assets/shared/draco_decoder.wasm", "./assets/flat1/preview.jpg", "./assets/flat2/preview.jpg"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// the app asks for one apartment to be kept: only an id that is in the cached list, only plain file names from its manifest
async function cacheFlat(flat) {
  const cache = await caches.open(CACHE);
  const list = await cache.match("./assets/flats.json").then((r) => (r ? r.json() : null));
  if (!list || !Array.isArray(list.flats) || !list.flats.some((f) => f && f.id === flat)) return 0;
  const res = await fetch("./assets/" + flat + "/manifest.json", { cache: "no-cache" });
  if (!res.ok) return 0;
  await cache.put("./assets/" + flat + "/manifest.json", res.clone());
  const files = (await res.json()).files;
  const urls = (Array.isArray(files) ? files : [])
    .filter((f) => f && typeof f.name === "string" && SAFE_NAME.test(f.name) && f.lazy !== true && f.preview !== true)
    .map((f) => "./assets/" + flat + "/" + f.name);
  const todo = [];
  for (const u of urls) if (!(await cache.match(u))) todo.push(u);
  await cache.addAll(todo);
  return urls.length;
}

self.addEventListener("message", (e) => {
  const m = e.data;
  if (!m || m.type !== "cache-flat" || typeof m.flat !== "string" || !FLAT_ID.test(m.flat)) return;
  e.waitUntil(
    cacheFlat(m.flat)
      .then((n) => { if (e.source) e.source.postMessage({ type: "cached", flat: m.flat, n }); })
      .catch(() => {})
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith(new URL(self.registration.scope).pathname)) return;
  // every load of the page (?flat=..., ?nolock ...) is the same document: keep one copy of it. Only the page: another document of this scope
  // (a licence file, assets/flats.json opened in a tab) is kept under its own request, so it can never stand in for the page offline
  const scope = new URL(self.registration.scope).pathname;
  const isPage = req.mode === "navigate" && (url.pathname === scope || url.pathname === scope + "index.html");
  const key = isPage ? "./index.html" : req;
  e.respondWith(
    fetch(req)
      .then((r) => {
        if (r.ok && r.type === "basic") {
          const copy = r.clone();
          caches.open(CACHE).then((c) => c.put(key, copy)).catch(() => {});
        }
        return r;
      })
      .catch(() => caches.open(CACHE).then((c) => c.match(key).then((m) => m || (isPage ? c.match("./index.html", { ignoreSearch: true }) : Response.error()))))
  );
});
